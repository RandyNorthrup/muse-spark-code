// Regenerates design/tui/art/* from media/icon.svg's squiggle path: the
// brand "m" (two humps, the second smaller, a flick, no loops) rasterized
// as quadrant blocks (.ans, brand-blue SGR) and density ASCII (.txt).
// Run: node scripts/tui-art.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ICON = path.join(ROOT, 'media/icon.svg')
const ART = path.join(ROOT, 'design/tui/art')
const BRAND = [0x3d, 0x8b, 0xff]

// Quadrant blocks: bit (x, y) of the 2x2 cell, y down.
const QUADRANTS = [' ', '▘', '▝', '▀', '▖', '▌', '▞', '▛', '▗', '▚', '▐', '▜', '▄', '▙', '▟', '█']
const ASCII_RAMP = [' ', '+', '+', '#', '#']

function pathPoints() {
  const svg = readFileSync(ICON, 'utf8')
  const d = svg.match(/d="([^"]+)"/)?.[1]
  if (!d) throw new Error('icon.svg has no path')
  return Array.from(d.matchAll(/([ML])([\d.]+) ([\d.]+)/g), (m) => ({
    move: m[1] === 'M',
    x: Number(m[2]),
    y: Number(m[3]),
  }))
}

function raster(points, cols, rows) {
  const xs = points.map((p) => p.x)
  const ys = points.map((p) => p.y)
  const [x0, x1] = [Math.min(...xs), Math.max(...xs)]
  const [y0, y1] = [Math.min(...ys), Math.max(...ys)]
  const W = cols * 2
  const H = rows * 2
  const ink = new Set()
  const plot = (x, y) => {
    const sx = Math.round(((x - x0) / (x1 - x0)) * (W - 1))
    const sy = Math.round(((y - y0) / (y1 - y0)) * (H - 1))
    // A 3-wide brush: a one-subpixel stroke reads as scattered dots at
    // terminal sizes, while the mark must read instantly.
    for (let dy = -1; dy <= 1; dy += 1) {
      for (let dx = -1; dx <= 1; dx += 1) {
        const px = sx + dx
        const py = sy + dy
        if (px >= 0 && px < W && py >= 0 && py < H) ink.add(py * W + px)
      }
    }
  }
  let pen = null
  for (const p of points) {
    if (pen === null || p.move) {
      pen = p
      plot(p.x, p.y)
      continue
    }
    // Walk the segment in subpixels so no curve gaps.
    const steps = Math.ceil(Math.hypot(p.x - pen.x, p.y - pen.y) * 8)
    for (let i = 1; i <= steps; i += 1) {
      plot(pen.x + ((p.x - pen.x) * i) / steps, pen.y + ((p.y - pen.y) * i) / steps)
    }
    pen = p
  }
  return { ink, W, H }
}

function render({ ink, W }, cols, rows, glyph) {
  const lines = []
  for (let row = 0; row < rows; row += 1) {
    let line = ''
    for (let col = 0; col < cols; col += 1) {
      const at = (dx, dy) => (ink.has((row * 2 + dy) * W + col * 2 + dx) ? 1 : 0)
      line += glyph(at(0, 0) | (at(1, 0) << 1) | (at(0, 1) << 2) | (at(1, 1) << 3))
    }
    lines.push(line.replaceAll(/\s+$/g, ''))
  }
  while (lines.length > 0 && lines.at(-1) === '') lines.pop()
  return lines
}

function main() {
  const points = pathPoints()
  mkdirSync(ART, { recursive: true })
  const sizes = [
    ['squiggle', 44, 12],
    ['squiggle-mini', 22, 6],
  ]
  const module = [
    '// Generated by scripts/tui-art.mjs from media/icon.svg. Do not edit.',
    '// The brand squiggle as line arrays: ANSI blocks and plain ASCII.',
  ]
  for (const [name, cols, rows] of sizes) {
    const grid = raster(points, cols, rows)
    const blocks = render(grid, cols, rows, (bits) => QUADRANTS[bits])
    const [r, g, b] = BRAND
    const ans = blocks
      .map((line) => (line === '' ? '' : `\u{1B}[38;2;${r};${g};${b}m${line}\u{1B}[0m`))
      .join('\n')
    const txt = render(
      grid,
      cols,
      rows,
      (bits) => ASCII_RAMP[[0, 1, 1, 2, 1, 2, 2, 3, 1, 2, 2, 3, 2, 3, 3, 4][bits]],
    ).join('\n')
    writeFileSync(path.join(ART, `${name}.ans`), `${ans}\n`)
    writeFileSync(path.join(ART, `${name}.txt`), `${txt}\n`)
    const symbol = name.replaceAll('-', '_').toUpperCase()
    module.push(
      `export const TUI_${symbol}_BLOCKS: readonly string[] = ${JSON.stringify(blocks)}`,
      `export const TUI_${symbol}_ASCII: readonly string[] = ${JSON.stringify(txt.split('\n'))}`,
    )
    console.log(`art: ${name} ${cols}x${rows}`)
  }
  writeFileSync(path.join(ROOT, 'design/tui/art.generated.ts'), `${module.join('\n')}\n`)
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main()
}
