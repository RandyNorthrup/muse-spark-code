// The lazy-bundle registry, written or checked FROM the build itself:
//
//   node scripts/gen-lazy-registry.mjs           writes src/shared/lazyBundles.generated.ts
//   node scripts/gen-lazy-registry.mjs --check   fails unless that file is current
//
// Run from the repository root after the production build. It reads the
// build's metafiles (dist/meta, dist/meta-acp) for the bundles and their
// import edges, the sources for every file they load by name
// (scripts/lib/lazyRegistry.mjs), the deferred redirect map for the bundle
// each lazy import resolves to, and each package's own inventory (vsce over
// the real .vscodeignore for the VSIX, scripts/lib/acpBundles.mjs for the
// agent).
//
// Both modes fail, with one sentence per problem, when the metafiles are
// missing, empty or unreadable; when a source loads a file the build does
// not emit; when a package lacks a bundle its side can load; when the VSIX
// carries a bundle only the agent loads; and when a load's file name is
// worked out at run time and is not listed with its reason. --check also
// fails when the committed file differs from what the build gives, and
// names each row that differs.
//
// This file is the command and nothing else: it has no exports and no
// "am I the main module" test, so it cannot be reached and do nothing.
import { cpSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { listFiles } from '@vscode/vsce/out/package.js'
import { format, resolveConfig } from 'prettier'
import { ACP_BUNDLES, acpUsageAssets } from './lib/acpBundles.mjs'
import { DEFERRED_OUTFILES } from './lib/deferredBundles.mjs'
import {
  NAMED_NOT_LOADED,
  computedLoadFailures,
  forwardSlashes,
  hasIdentifier,
  knownBundleOutputs,
  readMetafiles,
  resolveRequest,
  scanRequests,
} from './lib/lazyRegistry.mjs'

const root = process.cwd()
const GENERATED = 'src/shared/lazyBundles.generated.ts'
const METAFILE_DIRECTORIES = ['dist/meta', 'dist/meta-acp']
const WEBVIEW_HINTS = ['asWebviewUri', 'bundleRoot']
const DIST_PREFIX_LENGTH = 'dist/'.length
const EXIT_PROBLEMS = 1
const EXIT_USAGE = 2

const HEADER = `// Generated by \`node scripts/gen-lazy-registry.mjs\` (\`npm run
// lazy-registry:generate\`) from the production build's metafiles, the
// deferred redirect map and the sources' own loads; do not edit by hand.
// \`node scripts/gen-lazy-registry.mjs --check\` runs in \`npm run build\` and
// fails when this file differs from what the build gives, when a source
// loads a file the build does not emit, when a package lacks a bundle its
// side can load, or when a load's file name is worked out at run time and
// is not listed with its reason.
export interface LazyBundleRow {
  /** The bundle's path below dist/, e.g. 'tab.js' or 'webview/models.js'. */
  readonly file: string
  /**
  Which process loads it: the VS Code extension host, the agent, or both.
  A bundle no import edge and no load by file name reaches (an empty
  requestedBy) takes the side of the packages that carry it, and
  \`unreached\` when neither does.
  */
  readonly side: 'vscode' | 'acp' | 'both' | 'unreached'
  /**
  Every source that names it by file name: the file, the function, method
  or constant the name stands in, and the side that load needs. No line
  number: an unrelated edit of the source must not make this file stale.
  */
  readonly requestedBy: readonly {
    readonly importer: string
    readonly symbol: string
    readonly side: readonly ('vscode' | 'acp')[]
  }[]
}
`

const byName = (a, b) => a.localeCompare(b, 'en')

function fail(problems, summary) {
  for (const problem of problems) console.error(`lazy registry: ${problem}`)
  console.error(`lazy registry: ${summary}`)
  process.exit(EXIT_PROBLEMS)
}

async function vsixInventory() {
  const folder = mkdtempSync(path.join(tmpdir(), 'muse-lazy-registry-'))
  const inventory = path.join(folder, 'inventory')
  mkdirSync(inventory)
  const manifestFiles = ['package.json', '.vscodeignore']
  for (const file of manifestFiles) {
    cpSync(path.join(root, file), path.join(inventory, file))
  }
  cpSync(path.join(root, 'dist'), path.join(inventory, 'dist'), { recursive: true })
  try {
    const listed = await listFiles({ cwd: inventory, dependencies: false })
    return new Set(listed.map((file) => forwardSlashes(file)))
  } finally {
    await rm(folder, { recursive: true, force: true })
  }
}

function useLines(file, identifier) {
  if (identifier === undefined) return []
  const text = readFileSync(path.join(root, file), 'utf8').replaceAll('\r\n', '\n')
  return text.split('\n').filter((line) => hasIdentifier(line, identifier))
}

function sideName(sides) {
  if (sides.has('vscode') && sides.has('acp')) return 'both'
  const [only = 'unreached'] = sides
  return only
}

// The solid webview archive's members below dist/webview/, as the packager
// stages them (scripts/package-vsix.mjs): everything the build emits except
// the ACP agent's voice companion, which was never allowlisted into the
// VSIX and leaves the stage instead of joining the archive.
function webviewArchiveMembers() {
  const found = []
  const walk = (directory, prefix) => {
    const entries = readdirSync(directory, { withFileTypes: true })
    for (const entry of entries) {
      if (entry.isDirectory()) walk(path.join(directory, entry.name), `${prefix}${entry.name}/`)
      else if (entry.name !== 'voiceCompanion.js' && entry.name !== 'voiceCompanion.css')
        found.push(`${prefix}${entry.name}`)
    }
  }
  walk(path.join(root, 'dist', 'webview'), '')
  return found
}

async function buildRegistry() {
  const emitted = new Set()
  const inputChunks = new Map()
  const importEdges = new Map()
  for (const directory of METAFILE_DIRECTORIES) {
    readMetafiles(path.join(root, directory), root, emitted, inputChunks, importEdges)
  }
  const known = knownBundleOutputs(emitted)
  const reachable = emitted.union(known)
  const scan = scanRequests(root, GENERATED)
  const unread = []
  // Resolve every request: a redirect target, a dist file, or a bundled
  // import the build inlines (never a runtime load).
  const resolved = []
  const unknown = []
  // A name listed as spelled but not loaded (an OS launch path) gives no
  // load; its file must still be built and carried, checked below.
  const named = new Map()
  for (const request of scan.requests) {
    const at = `${request.importer}:${String(request.line)} (${request.symbol})`
    const entry = NAMED_NOT_LOADED.find(
      (item) =>
        item.importer === request.importer &&
        item.symbol === request.symbol &&
        item.value === request.value,
    )
    if (entry !== undefined) {
      named.set(entry, at)
      continue
    }
    const outcome = resolveRequest(root, DEFERRED_OUTFILES, request)
    if (outcome.bundled === true) continue
    const distFile = outcome.mapped ?? outcome.file ?? request.value
    const candidates = []
    for (const file of known) {
      if (file === `dist/${distFile}` || file.endsWith(`/${distFile}`)) candidates.push(file)
    }
    if (candidates.length === 0) {
      const want =
        typeof outcome.mapped === 'string' ? ` (redirect target dist/${outcome.mapped})` : ''
      unknown.push(`${at} loads ${request.value}${want}, which the build does not emit`)
      continue
    }
    // The load happens where the name is used, never where a shared constant
    // defines it: attribute the request to the files using it where a bundle
    // loads. A name nothing loads by (unused, or only framed/listed) is data,
    // never a request.
    let files = [request.importer]
    if (request.identifier !== undefined) {
      const used = scan.usesLoad.get(request.identifier) ?? []
      if (used.length === 0) {
        unread.push(`${at} defines ${request.identifier}, which no loader reads`)
        continue
      }
      files = used
    }
    const pick = (candidate) => {
      if (candidates.length === 1) return true
      const lines = []
      for (const file of files) {
        for (const line of useLines(file, request.identifier)) lines.push(line)
      }
      const isWebview = lines.some((line) => WEBVIEW_HINTS.some((hint) => line.includes(hint)))
      return candidate.startsWith('dist/webview/') === isWebview
    }
    const targets = candidates.filter((candidate) => pick(candidate))
    resolved.push({ request, at, files, targets })
  }
  // Sides propagate from the products' own entries: the manifest's main for
  // the VS Code extension host, the agent package's first bundle (its bin,
  // per scripts/lib/acpBundles.mjs) for the agent. Import edges and filename
  // requests carry each side to the chunks they can load.
  const manifest = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))
  const sides = new Map([
    [forwardSlashes(manifest.main.replace(/^\.\//u, '')), new Set(['vscode'])],
    [`dist/${ACP_BUNDLES[0]}`, new Set(['acp'])],
  ])
  const requestEdges = new Map()
  for (const item of resolved) {
    const from = new Set()
    for (const file of item.files) {
      const containing = inputChunks.get(file)
      if (containing === undefined) continue
      for (const chunk of containing) from.add(chunk)
    }
    for (const target of item.targets) {
      const sources = requestEdges.get(target) ?? new Set()
      for (const chunk of from) sources.add(chunk)
      requestEdges.set(target, sources)
    }
  }
  const pending = sides.keys().toArray()
  while (pending.length > 0) {
    const chunk = pending.pop()
    if (chunk === undefined) continue
    const out = new Set()
    const direct = importEdges.get(chunk)
    if (direct !== undefined) {
      for (const target of direct) out.add(target)
    }
    for (const [target, sources] of requestEdges) {
      if (sources.has(chunk)) out.add(target)
    }
    for (const target of out) {
      if (!reachable.has(target)) continue
      const reached = sides.get(target) ?? new Set()
      sides.set(target, reached)
      const before = reached.size
      const incoming = sides.get(chunk) ?? new Set()
      for (const side of incoming) reached.add(side)
      if (reached.size > before) pending.push(target)
    }
  }
  const vsix = await vsixInventory()
  // The webview ships as one solid archive (VSIXWEB A): the inventory
  // lists dist/webview.json.br instead of the loose members, but the VS Code
  // side loads them through the verified extraction, so the archive's
  // members count as carried. The stage always packs them (the loose files
  // leave with it), so this holds whether or not the check runs on a tree
  // whose dist/ already holds the archive file. The ACP agent's voice
  // companion never joined the VSIX (the same exclusion
  // scripts/package-vsix.mjs packs with), so it stays out here too.
  for (const member of webviewArchiveMembers()) vsix.add(`dist/webview/${member}`)
  // The agent carries the bundle list plus the usage page's asset closure,
  // exactly what scripts/package-acp.mjs stages.
  const agentFiles = [...ACP_BUNDLES]
  for (const file of acpUsageAssets(root)) agentFiles.push(file.replace(/^dist\//u, ''))
  const acp = new Set(agentFiles.map((file) => `dist/${file}`))
  const rows = new Map()
  const getRow = (file) => {
    const row = rows.get(file) ?? { file, requestedBy: new Map() }
    rows.set(file, row)
    return row
  }
  for (const file of known) getRow(file.slice(DIST_PREFIX_LENGTH))
  // A bundle only the agent provably loads is dead weight in the VSIX,
  // whose size budget every target must meet (PLAN.md D6, D209): the
  // agent's package carries it, the VSIX must not.
  const agentOnly = []
  // Bundles no process provably loads (no import edge, no filename request)
  // keep the side of the packages carrying them: removing a package could
  // break an invisible loader (the computed catalog adapter, an OS launcher).
  // requestedBy stays empty so the fallback is visible.
  for (const file of rows.keys()) {
    const reached = sides.get(`dist/${file}`) ?? new Set()
    if (reached.has('acp') && !reached.has('vscode') && vsix.has(`dist/${file}`))
      agentOnly.push(
        `the VSIX carries ${file}, which only the agent loads: drop it from .vscodeignore`,
      )
    if (reached.size > 0) continue
    const carrying = new Set()
    if (vsix.has(`dist/${file}`)) carrying.add('vscode')
    if (acp.has(`dist/${file}`)) carrying.add('acp')
    sides.set(`dist/${file}`, carrying)
  }
  // A request's loading sides: the fixpoint sides of the chunks containing
  // its files. A request from a file no chunk contains names a bundle no
  // process provably loads: both packages must carry it (fail closed).
  const gaps = []
  for (const item of resolved) {
    const at = new Set()
    for (const file of item.files) {
      const containing = inputChunks.get(file)
      if (containing === undefined) continue
      for (const chunk of containing) {
        const chunkSides = sides.get(chunk)
        if (chunkSides === undefined) continue
        for (const side of chunkSides) at.add(side)
      }
    }
    const loading = at.size > 0 ? at : new Set(['vscode', 'acp'])
    for (const target of item.targets) {
      const file = target.slice(DIST_PREFIX_LENGTH)
      const key = `${item.request.importer}\n${item.request.symbol}`
      const asked = getRow(file).requestedBy.get(key) ?? new Set()
      for (const side of loading) asked.add(side)
      getRow(file).requestedBy.set(key, asked)
      if (loading.has('vscode') && !vsix.has(target)) {
        gaps.push(`${item.at} loads ${file} in VS Code, and the VSIX does not carry it`)
      }
      if (loading.has('acp') && !acp.has(target)) {
        gaps.push(`${item.at} loads ${file} in the agent, and its package does not carry it`)
      }
    }
  }
  for (const entry of NAMED_NOT_LOADED) {
    const at = named.get(entry)
    const target = `dist/${entry.value}`
    if (at === undefined) {
      unknown.push(
        `NAMED_NOT_LOADED lists ${entry.value} in ${entry.importer} (${entry.symbol}), which the source no longer holds: remove the entry (scripts/lib/lazyRegistry.mjs)`,
      )
    } else if (!known.has(target)) {
      unknown.push(`${at} names ${entry.value}, which the build does not emit`)
    } else if (!(entry.carriedBy === 'acp' ? acp : vsix).has(target)) {
      gaps.push(
        `${at} names ${entry.value} for ${entry.carriedBy === 'acp' ? 'the agent, and its package' : 'VS Code, and the VSIX'} does not carry it`,
      )
    }
  }
  const list = rows
    .values()
    .map((row) => ({
      file: row.file,
      side: sideName(sides.get(`dist/${row.file}`) ?? new Set()),
      requestedBy: row.requestedBy
        .entries()
        .map(([key, asked]) => {
          const [importer = '', symbol = ''] = key.split('\n', 2)
          return { importer, symbol, side: asked.values().toArray().toSorted(byName) }
        })
        .toArray()
        .toSorted((a, b) => byName(a.symbol, b.symbol))
        .toSorted((a, b) => byName(a.importer, b.importer)),
    }))
    .toArray()
    .toSorted((a, b) => byName(a.file, b.file))
  return {
    rows: list,
    loads: resolved.length,
    listed: scan.computed.length,
    named: named.size,
    problems: [
      ...unknown.toSorted(byName),
      ...computedLoadFailures(scan.computed),
      ...new Set(gaps).values().toArray().toSorted(byName),
      ...agentOnly.toSorted(byName),
    ],
    unread: unread.toSorted(byName),
  }
}

async function render(rows) {
  const body = rows
    .map((row) => {
      const asked = row.requestedBy
        .map(
          (item) =>
            `{ importer: ${JSON.stringify(item.importer)}, symbol: ${JSON.stringify(item.symbol)}, side: ${JSON.stringify(item.side)} }`,
        )
        .join(', ')
      return `  { file: ${JSON.stringify(row.file)}, side: ${JSON.stringify(row.side)}, requestedBy: [${asked}] },`
    })
    .join('\n')
  const text = `${HEADER}\nexport const LAZY_BUNDLES: readonly LazyBundleRow[] = [\n${body}\n]\n`
  const target = path.join(root, GENERATED)
  const options = (await resolveConfig(target)) ?? {}
  return await format(text, { ...options, parser: 'typescript' })
}

/** Each row of a registry text, by its file, as one line of text. */
function rowsOf(text) {
  const found = new Map()
  let current = null
  for (const line of text.split('\n')) {
    if (current === null && line.startsWith('  {')) current = []
    if (current === null) continue
    current.push(line.trim())
    if (!/^ {2}\},?$|^ {2}\{.*\},?$/u.test(line)) continue
    const row = current.join(' ')
    const file = /file: (['"])([^'"]+)\1/u.exec(row)?.[2]
    if (file !== undefined) found.set(file, row)
    current = null
  }
  return found
}

/** One sentence per row in which the committed file and the build differ. */
function differences(committed, generated) {
  const before = rowsOf(committed)
  const after = rowsOf(generated)
  const found = []
  for (const [file, row] of after) {
    const old = before.get(file)
    if (old === undefined) found.push(`${GENERATED} has no row for ${file}; the build gives ${row}`)
    else if (old !== row) found.push(`${GENERATED} row ${file} says ${old}; the build gives ${row}`)
  }
  for (const file of before.keys()) {
    if (!after.has(file))
      found.push(`${GENERATED} has a row for ${file}, which the build no longer gives`)
  }
  if (found.length === 0) {
    found.push(
      `${GENERATED} differs from the generated text outside its rows (its header or its formatting)`,
    )
  }
  return found
}

const argv = process.argv.slice(2)
const isCheck = argv.includes('--check')
if (argv.some((argument) => argument !== '--check')) {
  console.error('gen-lazy-registry [--check]')
  process.exit(EXIT_USAGE)
}
const remedy = `not ${isCheck ? 'checked' : 'written'}`

// No input, no pass: without the build's metafiles there is nothing to
// compare the sources with.
for (const directory of METAFILE_DIRECTORIES) {
  let names
  try {
    names = readdirSync(path.join(root, directory))
  } catch (error) {
    fail(
      [
        `${directory} cannot be read (${error instanceof Error ? error.message : String(error)}); run the production build first (node scripts/build.mjs --production)`,
      ],
      `${GENERATED} ${remedy}`,
    )
  }
  if (names.every((name) => !name.endsWith('.json'))) {
    fail(
      [
        `${directory} holds no metafile; run the production build first (node scripts/build.mjs --production)`,
      ],
      `${GENERATED} ${remedy}`,
    )
  }
}

let registry
try {
  registry = await buildRegistry()
} catch (error) {
  fail(
    [
      `the registry cannot be built from this tree: ${error instanceof Error ? error.message : String(error)}`,
    ],
    `${GENERATED} ${remedy}`,
  )
}
const content = await render(registry.rows)
const problems = [...registry.problems]
if (isCheck) {
  let committed
  try {
    committed = readFileSync(path.join(root, GENERATED), 'utf8').replaceAll('\r\n', '\n')
  } catch (error) {
    problems.push(
      `${GENERATED} cannot be read (${error instanceof Error ? error.message : String(error)})`,
    )
  }
  if (committed !== undefined && committed !== content) {
    problems.push(...differences(committed, content))
  }
}
if (problems.length > 0) {
  fail(
    problems,
    `${String(problems.length)} problem(s); ${GENERATED} ${remedy}${isCheck ? ' as current; after a real change of loaders run npm run lazy-registry:generate' : ''}`,
  )
}
if (!isCheck) writeFileSync(path.join(root, GENERATED), content)
for (const note of registry.unread) console.log(`lazy registry note: ${note}`)
console.log(
  `ok   lazy registry: ${String(registry.rows.length)} bundles, ${String(registry.loads)} loads by file name resolved, ${String(registry.listed)} listed load(s) by a computed name, ${String(registry.named)} listed name(s) that are not a load; ${GENERATED} ${isCheck ? 'is current' : 'written'}`,
)
