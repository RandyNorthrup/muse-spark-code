#!/usr/bin/env node
// Generate the feature reference from catalogued README sections. --check
// detects stale help without writing; the catalog carries no runtime UI.
import { Buffer } from 'node:buffer'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { build } from 'esbuild'

const { outputFiles } = await build({
  entryPoints: ['src/shared/featureCatalog.ts'],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  logLevel: 'silent',
})
const { FEATURE_CATALOG } = await import(
  `data:text/javascript;base64,${Buffer.from(outputFiles[0].contents).toString('base64')}`
)
const source = readFileSync('README.md', 'utf8')
const sections = FEATURE_CATALOG.map(({ id }) => {
  const start = `<!-- reference: ${id} -->`
  const end = `<!-- /reference: ${id} -->`
  const at = source.indexOf(start)
  const until = source.indexOf(end, at + start.length)
  if (at === -1 || until === -1 || source.includes(start, at + start.length)) {
    throw new Error(`Missing or duplicate README reference section: ${id}`)
  }
  return source.slice(at + start.length, until).trim()
})
const file = path.join('docs', 'reference.md')
const text =
  [
    '# Feature reference',
    '<!-- Generated by scripts/gen-reference.mjs; edit the marked README sections. -->',
    'This reference covers the catalogued entries. See [the README](../README.md)\nfor the complete guide.',
    ...sections,
  ].join('\n\n') + '\n'
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') === text) {
    process.stdout.write('Feature reference is current.\n')
  } else {
    process.stderr.write('Feature reference is stale. Run node scripts/gen-reference.mjs.\n')
    process.exitCode = 1
  }
} else {
  writeFileSync(file, text)
  process.stdout.write(`Wrote ${file}.\n`)
}
