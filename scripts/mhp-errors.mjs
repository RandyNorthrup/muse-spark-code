// Both native hosts consume the frozen schema's error codes and these shared
// technical aliases. No host maintains its own allowlist or numeric mapping.
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const root = path.resolve(import.meta.dirname, '..')
const aliases = {
  MHP_CAPABILITY_UNAVAILABLE: 'unsupportedCapability',
  MHP_DIRTY_DOCUMENT: 'dirtyBuffer',
  MHP_INVALID_RANGE: 'invalidParams',
  MHP_OVERLAPPING_EDITS: 'invalidParams',
}

export async function generateMhpErrors(check) {
  const schema = JSON.parse(
    await readFile(path.join(root, 'src/shared/hostApi/mhp-v1.1.schema.json'), 'utf8'),
  )
  const codes = schema.errorCodes
  const entries = Object.entries(codes).map(([name, code]) => [
    `MHP_${name.replaceAll(/[A-Z]/gu, (letter) => `_${letter}`).toUpperCase()}`,
    code,
  ])
  for (const [name, target] of Object.entries(aliases)) {
    if (!Object.hasOwn(codes, target)) throw new Error(`MHP_ERROR_ALIAS_UNKNOWN: ${target}`)
    entries.push([name, codes[target]])
  }
  const constants = new Map(
    entries
      .slice(0, Object.keys(codes).length)
      .map(([name, code]) => [code, name.slice('MHP_'.length)]),
  )
  const banner = '// Generated by scripts/mhp-errors.mjs from the frozen MHP schema. Do not edit.\n'
  const java = `${banner}package io.musespark.eclipse;

import java.util.Map;

public final class MhpErrors {
    private MhpErrors() { }
${[...constants].map(([code, name]) => `    private static final int ${name} = ${code};`).join('\n')}
    private static final Map<String, Integer> CODES = Map.ofEntries(
${entries.map(([name, code]) => `        Map.entry("${name}", ${constants.get(code)})`).join(',\n')}
    );
    public static String technicalCode(Throwable failure) {
        String message = failure.getMessage();
        return message != null && CODES.containsKey(message) ? message : "MHP_INTERNAL_ERROR";
    }
    public static int numeric(String code) { return CODES.getOrDefault(code, CODES.get("MHP_INTERNAL_ERROR")); }
}
`
  const kotlin = `${banner}package io.github.randynorthrup.musespark

object MhpErrors {
${[...constants].map(([code, name]) => `  private const val ${name} = ${code}`).join('\n')}
  private val codes =
    mapOf(
${entries.map(([name, code]) => `      "${name}" to ${constants.get(code)},`).join('\n')}
    )

  fun technicalCode(failure: Throwable): String = failure.message?.takeIf { it in codes } ?: "MHP_INTERNAL_ERROR"

  fun numeric(code: String): Int = codes[code] ?: codes.getValue("MHP_INTERNAL_ERROR")
}
`
  for (const [file, bytes] of [
    ['hosts/eclipse/plugin/src/io/musespark/eclipse/MhpErrors.java', java],
    ['hosts/jetbrains/src/main/kotlin/io/github/randynorthrup/musespark/MhpErrors.kt', kotlin],
  ]) {
    const target = path.join(root, file)
    if (check) {
      if ((await readFile(target, 'utf8')) !== bytes)
        throw new Error(`MHP_ERROR_TABLE_DRIFT: ${file}`)
    } else await writeFile(target, bytes)
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await generateMhpErrors(process.argv.includes('--check'))
  console.log(
    process.argv.includes('--check') ? 'MHP error tables match.' : 'MHP error tables written.',
  )
}
