-- Manual installed-host qualification probe; a missing bootstrap must fail.
local root = vim.fs.normalize(vim.fn.getcwd())
local receipt_path = root .. '/temp/neovim-bootstrap.json'
vim.fn.mkdir(root .. '/temp', 'p')
vim.fn.delete(receipt_path)
vim.opt.rtp:prepend(root .. '/hosts/neovim')
local muse = require('muse')
muse.setup({command = {'python3', root .. '/test/m104/linux/shims/handshake.py', receipt_path}})
local ok, failure = xpcall(function()
  muse.open_companion()
  assert(vim.wait(4000, function() return vim.fn.filereadable(receipt_path) == 1 end), 'Receipt missing')
  local receipt = vim.json.decode(table.concat(vim.fn.readfile(receipt_path), '\n'))
  assert(not receipt.credential_variable_present, 'Credential variable reached fake peer')
  assert(receipt.initialized, 'MHP_13_BOOTSTRAP_MISSING')
end, debug.traceback)
local stopped, stop_failure = pcall(muse.stop)
assert(stopped, stop_failure)
assert(ok, failure)
