import { mkdtemp, mkdir, readFile, rm, writeFile, copyFile, symlink } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import process from 'node:process'
import { promisify } from 'node:util'
import { build } from 'esbuild'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { usageLocalDay } from '../../src/core/usage/aggregate'
import { UsageJournalStore } from '../../src/core/usage/journalStore'
import { NodeUsageFs } from '../../src/runtime/usage/nodeUsageFs'
import {
  agentDataFolder,
  workspaceSessionsFolder,
  type DataFolderInput,
} from '../../src/runtime/dataFolder'

const run = promisify(execFile)
const state = { root: '', command: '', live: '', liveCommand: '', liveData: '' }
const sourceRoot = path.resolve(import.meta.dirname, '../..')
// A fixed stamp keeps every generated byte deterministic.
const LIVE_AS_OF = '2026-10-07T12:00:00Z'
const LIVE_SESSION_ID = 'e2esession'

beforeAll(async () => {
  state.root = await mkdtemp(path.join(os.tmpdir(), 'm113-reports-cli-'))
  state.command = path.join(state.root, 'dist', 'acp.js')
  await mkdir(path.join(state.root, 'dist'))
  await mkdir(path.join(state.root, 'l10n'))
  await writeFile(path.join(state.root, 'package.json'), JSON.stringify({ version: '0.14.2' }))
  await copyFile(
    path.join(sourceRoot, 'test/fixtures/reports/project.json.golden'),
    path.join(state.root, 'fixture.json'),
  )
  await copyFile(path.join(sourceRoot, 'l10n/ui.de.json'), path.join(state.root, 'l10n/ui.de.json'))
  // One memoized build per suite; each child runs the real runtime main and lazy loader.
  await build({
    entryPoints: [path.join(sourceRoot, 'src/runtime/main.ts')],
    outfile: state.command,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    external: ['@napi-rs/keyring'],
    logLevel: 'silent',
  })
  await build({
    entryPoints: [path.join(sourceRoot, 'test/e2e/reportsEntry.ts')],
    outfile: path.join(state.root, 'dist/reporting.js'),
    bundle: true,
    platform: 'node',
    format: 'cjs',
    logLevel: 'silent',
  })
  // C-M113-2: a second CLI keeps production's own engine construction, so the
  // cases below run the real session and usage bindings end to end.
  state.live = path.join(state.root, 'live')
  state.liveData = path.join(state.root, 'livedata')
  const liveDist = path.join(state.live, 'dist')
  await mkdir(liveDist, { recursive: true })
  await writeFile(path.join(state.live, 'package.json'), JSON.stringify({ version: '0.14.2' }))
  await build({
    entryPoints: [path.join(sourceRoot, 'src/runtime/main.ts')],
    outfile: path.join(liveDist, 'acpLive.js'),
    bundle: true,
    platform: 'node',
    format: 'cjs',
    external: ['@napi-rs/keyring'],
    logLevel: 'silent',
  })
  await build({
    entryPoints: [path.join(sourceRoot, 'src/runtime/reporting/reportsEntry.ts')],
    outfile: path.join(liveDist, 'reporting.js'),
    bundle: true,
    platform: 'node',
    format: 'cjs',
    external: ['@napi-rs/keyring'],
    logLevel: 'silent',
  })
  await build({
    entryPoints: [path.join(sourceRoot, 'src/runtime/reporting/reportInputsEntry.ts')],
    outfile: path.join(liveDist, 'reportInputs.js'),
    bundle: true,
    platform: 'node',
    format: 'cjs',
    logLevel: 'silent',
  })
  // An isolated data folder: the live CLI must never read the developer's own
  // journal or sessions, and the numbers below must be exactly these fixtures.
  const home = path.join(state.liveData, 'home')
  const input: DataFolderInput = {
    platform: process.platform,
    env: { XDG_DATA_HOME: path.join(state.liveData, 'data') },
    homeDir: home,
  }
  const sessions = workspaceSessionsFolder(input, state.live)
  await mkdir(sessions, { recursive: true })
  await writeFile(
    path.join(sessions, `${LIVE_SESSION_ID}.json`),
    JSON.stringify({
      version: 1,
      sessionId: LIVE_SESSION_ID,
      workspaceRoot: state.live,
      modelId: 'e2e-model',
      approvalMode: 'promptUnmatched',
      effort: 'normal',
      createdAt: LIVE_AS_OF,
      lastActivityAt: LIVE_AS_OF,
      turnIds: ['t1'],
      todos: [],
      replay: [],
      transcript: [
        {
          turnId: 't1',
          item: {
            itemId: 'u1',
            kind: 'userMessage',
            status: 'completed',
            turnId: 't1',
            text: 'Hello live session',
          },
        },
      ],
      outputs: {},
      usage: { inputTokens: 0, outputTokens: 0, cachedTokens: 0, reasoningTokens: 0 },
    }),
  )
  const journal = new UsageJournalStore(new NodeUsageFs(agentDataFolder(input)), {
    writerId: 'e2e-writer',
    now: () => Date.parse(LIVE_AS_OF),
    isEnabled: () => true,
    onWriteError: () => {
      throw new Error('e2e journal write failed')
    },
  })
  journal.append({
    v: 1,
    type: 'usage',
    id: 'e2e-r1',
    at: Date.parse(LIVE_AS_OF),
    day: usageLocalDay(Date.parse(LIVE_AS_OF)),
    timezoneOffsetMins: 0,
    client: 'acp',
    backend: 'modelApi',
    provider: 'meta',
    model: 'e2e-model',
    kind: 'turn',
    tokens: { input: 200, output: 10 },
    cost: { usd: 0.5, certainty: 'reported' },
    outcome: 'completed',
    startedAt: Date.parse(LIVE_AS_OF),
    session: LIVE_SESSION_ID,
  })
  await journal.flush()
})

afterAll(async () => {
  await rm(state.root, { recursive: true, force: true })
})

async function runCli(
  command: string,
  args: readonly string[],
  cwd: string,
  env: NodeJS.ProcessEnv,
) {
  try {
    const result = await run(process.execPath, [command, 'report', ...args], { cwd, env })
    return { code: 0, stdout: result.stdout, stderr: result.stderr }
  } catch (error: unknown) {
    if (
      typeof error !== 'object' ||
      error === null ||
      !('code' in error) ||
      !('stdout' in error) ||
      !('stderr' in error)
    )
      throw error
    return { code: error.code, stdout: error.stdout, stderr: error.stderr }
  }
}

async function cli(args: readonly string[]) {
  // No credential variables are inherited; no keyring or backend is invoked.
  return await runCli(state.command, args, state.root, {
    PATH: process.env['PATH'],
    SystemRoot: process.env['SystemRoot'],
    LC_ALL: 'en_US.UTF-8',
  })
}

async function liveCli(args: readonly string[]) {
  // An isolated data folder: the live CLI must never read the developer's
  // own journal or sessions.
  const home = path.join(state.liveData, 'home')
  const data = path.join(state.liveData, 'data')
  return await runCli(path.join(state.live, 'dist', 'acpLive.js'), args, state.live, {
    PATH: process.env['PATH'],
    SystemRoot: process.env['SystemRoot'],
    LC_ALL: 'en_US.UTF-8',
    HOME: home,
    USERPROFILE: home,
    XDG_DATA_HOME: data,
    LOCALAPPDATA: data,
  })
}

describe('reports CLI subprocess', () => {
  // One child build is shared in beforeAll; each case below stays at two
  // sequential invocations so slower rigs keep the default deadline.
  it.each(['md', 'html', 'json', 'text'] as const)(
    're-renders saved format %s byte for byte and saves exact output',
    async (format) => {
      const expected = await readFile(
        path.join(
          sourceRoot,
          'test/fixtures/reports',
          format === 'html' ? 'project.cli.html.golden' : `project.${format}.golden`,
        ),
        'utf8',
      )
      const result = await cli(['--from', 'fixture.json', '--format', format])
      expect(result).toEqual({ code: 0, stdout: expected, stderr: '' })
      const out = `saved.${format}`
      expect(await cli(['--from', 'fixture.json', '--format', format, '--out', out])).toEqual({
        code: 0,
        stdout: '',
        stderr: '',
      })
      expect(await readFile(path.join(state.root, out), 'utf8')).toBe(expected)
    },
  )

  it('generates with a fixed as-of and holds a strict condition without model output', async () => {
    expect(await cli(['project', '--as-of', '2026-10-06T12:00:00+00:00'])).toMatchObject({
      code: 0,
    })
    const held = await cli(['project', '--strict'])
    expect(held.code).toBe(4)
    expect(held.stdout).toEqual(expect.stringContaining('Needs you'))
    expect(held.stderr).toBe('')
  })

  it('returns usage and failure codes without model output', async () => {
    expect(
      await cli(['project', '--out', path.join(state.root, 'missing', 'file.md')]),
    ).toMatchObject({ code: 1 })
    expect(await cli(['project', '--format', 'yaml'])).toMatchObject({ code: 2 })
  })

  it('returns not-found for an unknown milestone scope', async () => {
    expect(await cli(['milestone', 'M999'])).toMatchObject({ code: 3 })
  })

  it('rejects damaged JSON and linked saved imports without echoing file contents', async () => {
    await writeFile(path.join(state.root, 'broken.json'), '{ CANARY-never-echo')
    expect(await cli(['--from', 'broken.json'])).toEqual({
      code: 1,
      stdout: '',
      stderr: 'The report could not be generated.\n',
    })
    await symlink(path.join(state.root, 'fixture.json'), path.join(state.root, 'linked.json'))
    expect(await cli(['--from', 'linked.json'])).toMatchObject({ code: 1 })
  })

  it('uses a real installed translation and leaves collection inactive for --from', async () => {
    const result = await cli(['--from', 'fixture.json', '--lang', 'de'])
    expect(result.code).toBe(0)
    expect(result.stdout).toEqual(expect.stringContaining('# Projekt'))
    expect(result.stderr).not.toEqual(expect.stringContaining('backend'))
  })
})

describe('session and usage report kinds over real journals', () => {
  it('reports a stored session end to end with its journal usage', async () => {
    const result = await liveCli(['session', '--session', LIVE_SESSION_ID, '--as-of', LIVE_AS_OF])
    expect(result.code).toBe(0)
    // The transcript travels in the export; the rendered rows carry the rest.
    expect(result.stdout).toEqual(expect.stringContaining('e2e-model'))
    expect(result.stdout).toEqual(expect.stringContaining('| 1 | Available |'))
  })

  it.each([
    ['model', 'meta/e2e-model'],
    ['provider', '| meta |'],
    ['kind', '| turn |'],
    ['client', '| acp |'],
    ['session', 'e2esession'],
    ['account', 'default'],
  ] as const)('reports usage grouped by %s', async (by, key) => {
    const result = await liveCli(['usage', '--as-of', LIVE_AS_OF, '--by', by])
    expect(result.code).toBe(0)
    expect(result.stdout).toEqual(expect.stringContaining(key))
  })

  it('reports per-tool usage as partial instead of inventing rows', async () => {
    const result = await liveCli(['usage', '--as-of', LIVE_AS_OF, '--by', 'tool'])
    expect(result.code).toBe(0)
    expect(result.stdout).toEqual(
      expect.stringContaining('Per-tool usage is not recorded in the usage journal.'),
    )
  })

  it('reports an unknown session as unavailable without failing', async () => {
    const result = await liveCli(['session', '--session', 'ghost', '--as-of', LIVE_AS_OF])
    expect(result.code).toBe(0)
    expect(result.stdout).toEqual(
      expect.stringContaining('History for the selected session is unavailable.'),
    )
  })
})
