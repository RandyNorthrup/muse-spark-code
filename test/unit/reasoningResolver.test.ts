// Lane REASONSHAPES: `ultra` rides in EFFORT_LEVELS now (no explicit tail).
const SETTINGS = ['none', ...EFFORT_LEVELS] as const

/** `effortForPolicy` exactly as rel017/dsthink's base 01ee6233b shipped it. */
function baseEffortForPolicy(policy: ModelPolicy, requested: string): string {
  if (policy.identity.provider === 'meta') {
    return requested === 'none' ? 'minimal' : requested
  }
  const levels = policy.reasoning.effortLevels
  return levels.state === 'yes' && levels.value.includes(requested) ? requested : 'none'
}

describe('resolveReasoning', () => {
  const SWITCH: ReasoningControl = {
    effortLevels: ['low', 'high', 'max'],
    canDisable: true,
    thinkingOff: 'thinking-switch',
  }
  it.each([
    // [model, requested, decision]
    [SWITCH, 'none', { kind: 'off' }],
    [SWITCH, 'high', { kind: 'effort', effort: 'high' }],
    [SWITCH, 'minimal', { kind: 'effort', effort: 'low' }],
    [SWITCH, 'medium', { kind: 'effort', effort: 'high' }],
    [SWITCH, 'xhigh', { kind: 'effort', effort: 'max' }],
    // `ultra` is unlisted here, so the nearest listed level answers.
    [SWITCH, 'ultra', { kind: 'effort', effort: 'max' }],
    [
      { ...SWITCH, canDisable: false },
      'none',
      { kind: 'refuse', code: 'unsupported_reasoning_effort' },
    ],
    [{ ...SWITCH, effortLevels: undefined }, 'none', { kind: 'off' }],
    [{ ...SWITCH, effortLevels: undefined }, 'high', { kind: 'default' }],
    [{ ...SWITCH, effortLevels: [] }, 'medium', { kind: 'default' }],
    [{ ...SWITCH, effortLevels: ['none'] }, 'low', { kind: 'default' }],
    [
      { effortLevels: undefined, canDisable: false, thinkingOff: 'thinking-switch' },
      'none',
      { kind: 'refuse', code: 'unsupported_reasoning_effort' },
    ],
    [{ ...SWITCH, thinkingOff: undefined }, 'high', { kind: 'effort', effort: 'high' }],
    [{ ...SWITCH, thinkingOff: undefined }, 'medium', { kind: 'default' }],
    [{ ...SWITCH, thinkingOff: undefined }, 'none', { kind: 'off' }],
    [{ ...SWITCH, thinkingOff: undefined, canDisable: false }, 'none', { kind: 'off' }],
    [
      { ...SWITCH, thinkingOff: undefined, effortLevels: ['none'] },
      'none',
      { kind: 'effort', effort: 'none' },
    ],
  ] as const)('%o + %s', (model, requested, decision) => {
    expect(resolveReasoning(model, requested)).toEqual(decision)
  })

  it('never maps a Thinking-on setting to off', () => {
    for (const effortLevels of [undefined, [], ['low'], ['max'], ['low', 'high', 'max']])
      for (const canDisable of [true, false])
        for (const requested of EFFORT_LEVELS)
          expect(
            resolveReasoning(
              { effortLevels, canDisable, thinkingOff: 'thinking-switch' },
              requested,
            ).kind,
          ).not.toBe('off')
  })
})

/** One entry per preset; catalogue presets list every model the snapshot gives them. */
async function presetEntries(): Promise<ProviderEntry[]> {
  const catalogue = JSON.parse(
    await readFile(path.resolve('vendor/models-dev/snapshot.json'), 'utf8'),
  ) as { providers: Record<string, { models: Record<string, unknown> }> }
  return [...PRESETS, ...PLAN_KEY_PRESETS].map((preset) => {
    const listed = Object.keys(catalogue.providers[preset.id.replace('-plan', '')]?.models ?? {})
    const models = listed.length > 0 ? listed : ['table-model']
    let address = 'https://llm.example.test'
    switch (preset.origin.kind) {
      case 'fixed': {
        address = preset.origin.origin
        break
      }
      case 'loopback': {
        address = `http://127.0.0.1:${String(preset.origin.defaultPort)}`
        break
      }
      case 'azure-resource': {
        address = 'https://table.openai.azure.com'
        break
      }
      default: {
        break
      }
    }
    return providerEntrySchema.parse({
      id: preset.id,
      preset: preset.id,
      address,
      format: preset.format,
      auth: preset.auth,
      models,
      ...(preset.id === 'ollama' && { numCtx: { 'table-model': 8192 } }),
      ...(preset.id === 'custom' && {
        modelLimits: { 'table-model': { contextTokens: 128_000, outputTokens: 8192 } },
      }),
    })
  })
}

describe('every preset model × every setting against base 01ee6233b', () => {
  let root = ''
  const policies = new Map<string, ModelPolicy>()
  let deps: ProviderRegistryDeps
  let rows: readonly RegistryModel[] = []
  const sent: string[] = []

  /**
   * One line per model and setting: the exact request bytes the production
   * client dispatched, or why it sent none. Request bytes vary by model only
   * through its evidence, so one model per distinct evidence class keeps
   * every dispatch shape in the table.
   */
  async function wireLines(preset: string): Promise<string[]> {
    const lines: string[] = []
    const classes = new Set<string>()
    for (const row of rows) {
      if (row.ref.split('/', 1)[0] !== preset) continue
      const evidenceClass = JSON.stringify(row.evidence)
      if (classes.has(evidenceClass)) continue
      classes.add(evidenceClass)
      let client: Awaited<ReturnType<ProviderRegistryDeps['createClient']>>
      try {
        client = await deps.createClient(row)
      } catch (error) {
        lines.push(`${row.ref}\tno client: ${String(error)}`)
        continue
      }
      const policy = policies.get(row.ref) ?? fail()
      for (const setting of SETTINGS) {
        sent.length = 0
        let outcome = ''
        try {
          await Array.fromAsync(
            client.streamResponse(
              { ...BODY, model: row.ref, reasoning: { effort: effortForPolicy(policy, setting) } },
              new AbortController().signal,
            ),
          )
        } catch (error) {
          outcome = String(error)
        }
        lines.push(`${row.ref}\t${setting}\t${sent.at(-1) ?? '-'}\t${outcome}`)
      }
    }
    return lines
  }
  beforeAll(async () => {
    root = await mkdtemp(path.join(tmpdir(), 'dsthink3-table-'))
    const entries = await presetEntries()
    const configFile = path.join(root, 'providers.json')
    const written = await writeProvidersFileAtomic(configFile, { v: 1, providers: entries })
    expect(written.ok).toBe(true)
    const secrets = memorySecrets()
    for (const entry of entries)
      if (entry.auth === 'apiKey')
        await secrets.store(
          `${PROVIDER_SECRET_PREFIX}${entry.id}`,
          formatStoredProviderSecret(
            { v: 1, auth: 'apiKey', origin: new URL(entry.address ?? '').origin },
            'test-owned-key',
          ),
        )
    createConfiguredProviderServices(undefined, {
      secrets,
      configFile,
      catalogFile: path.resolve('vendor/models-dev/snapshot.json'),
      resolve: () => Promise.resolve(['8.8.8.8']),
      send: (_target, bytes) => {
        if (bytes !== undefined) sent.push(bytes)
        return Promise.resolve(DONE())
      },
    })
    // The registry's own join (providerRegistry.ts resolve), over one read of
    // the configured rows instead of one file and catalogue read per model.
    deps = registryDeps.at(-1) ?? fail()
    rows = await deps.models()
    for (const row of rows)
      policies.set(row.ref, modelPolicyFor(row.ref, { ...row.evidence, pricing: row.pricing }))
  })
  afterAll(() => rm(root, { recursive: true, force: true }))

  it('covers every preset', () => {
    expect(new Set(Array.from(policies.keys(), (ref) => ref.split('/', 1)[0]))).toEqual(
      new Set([...PRESETS, ...PLAN_KEY_PRESETS].map((preset) => preset.id)),
    )
  })

  it('sends every other preset model the base effort for every setting', () => {
    let compared = 0
    for (const [ref, policy] of policies) {
      if (policy.reasoning.thinkingOff !== undefined) continue
      // Lane REASONSHAPES: llama.cpp documents its effort vocabulary for
      // every model, so declared tiers ride as named instead of the base.
      if (ref.startsWith('llamacpp/')) continue
      for (const setting of SETTINGS) {
        expect([ref, setting, effortForPolicy(policy, setting)]).toEqual([
          ref,
          setting,
          baseEffortForPolicy(policy, setting),
        ])
        compared += 1
      }
    }
    expect(compared).toBeGreaterThan(600 * SETTINGS.length)
  })

  it('passes llama.cpp tiers through as named, with none disabling', () => {
    // Lane REASONSHAPES (LO-G04, LO-G05): the server routes
    // `reasoning_effort` to the chat template; `none` disables.
    for (const [ref, policy] of policies) {
      if (!ref.startsWith('llamacpp/')) continue
      for (const setting of SETTINGS) {
        expect(effortForPolicy(policy, setting)).toBe(setting)
      }
    }
  })

  it('declares the Thinking-off switch on DeepSeek, Z.ai and Together', () => {
    // Lane REASONSHAPES: DeepSeek's thinking-mode switch, Z.ai's
    // `thinking.type` switch and Together's hybrid toggle, each read off
    // the provider's own documentation page on 2026-10-12.
    const switched = [...policies].filter(
      ([, policy]) => policy.reasoning.thinkingOff !== undefined,
    )
    expect(switched.length).toBeGreaterThan(0)
    const byPreset = new Map<string, string>()
    for (const [ref, policy] of switched) {
      byPreset.set(ref.split('/', 1)[0] ?? ref, policy.reasoning.thinkingOff ?? '')
    }
    expect([...byPreset]).toEqual([
      ['deepseek', 'thinking-switch'],
      ['together', 'reasoning-enabled'],
      ['zai', 'thinking-switch'],
    ])
  })
  it.each(OTHER_PRESETS)(
    '%s dispatches the base request bytes for every model and setting',
    async (preset) => {
      const lines = await wireLines(preset)
      const digest = {
        lines: lines.length,
        sha256: createHash('sha256').update(lines.join('\n')).digest('hex'),
      }
      expect(digest).toEqual(BASE_WIRE[preset])
    },
  )
})
