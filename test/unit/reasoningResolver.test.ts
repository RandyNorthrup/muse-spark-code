const BASE_WIRE = z
  .record(z.string(), z.object({ lines: z.number(), sha256: z.string() }))
  .parse(
    JSON.parse(readFileSync(new URL('reasoningResolverBaseWire.json', import.meta.url), 'utf8')),
  )
const OTHER_PRESETS = [...PRESETS, ...PLAN_KEY_PRESETS]
  .map((preset) => preset.id)
