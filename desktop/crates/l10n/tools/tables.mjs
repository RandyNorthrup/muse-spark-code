// Muse Desktop (M111, D91.20) lane IN: the desktop's language tables,
// generated from the same English table and fourteen translated tables the
// extension reads, so native Rust code and the Qt Quick shell show the same
// words. `ui_text!` (desktop/crates/l10n/src/lib.rs) reads the Rust table;
// the shell reads the generated QML singleton. `check:l10n` keeps both
// outputs fresh and scans Rust and QML sources for unknown keys.

import { readFileSync } from 'node:fs'
import path from 'node:path'
import { loadL10n } from '../../../../scripts/lib/l10nSource.mjs'

export const RUST_TABLES_FILE = 'desktop/crates/l10n/src/tables.rs'
export const QML_SINGLETON_FILE = 'desktop/crates/l10n/qml/UiText.qml'
export const QML_MODULE = 'MuseL10n'
export const ENGLISH_LOCALE = 'en'

function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/**
Every plain string of a table as a dotted key, in the table's own order. A
plural entry becomes one dotted key per form (`agentsCount.one`), since Rust
and QML callers name the form they show; the whole object is not a string.
*/
export function flattenTable(table, isPluralForms, prefix = '') {
  return Object.entries(table).flatMap(([name, value]) => {
    const key = `${prefix}${name}`
    if (typeof value === 'string') return [[key, value]]
    if (isPluralForms(value)) {
      return Object.entries(value).map(([form, text]) => [`${key}.${form}`, text])
    }
    return isRecord(value) ? flattenTable(value, isPluralForms, `${key}.`) : []
  })
}

function escapeRust(text) {
  return (
    text
      // A lone backslash cannot be written in String.raw (it would escape
      // the closing backtick), so only the replacements use it.
      .replaceAll('\\', String.raw`\\`)
      .replaceAll('"', String.raw`\"`)
      .replaceAll('\n', String.raw`\n`)
      .replaceAll('\r', String.raw`\r`)
      .replaceAll('\t', String.raw`\t`)
  )
}

function rustEntry([key, value]) {
  return `        ("${escapeRust(key)}", "${escapeRust(value)}"),`
}

function renderRust(locales, flattened) {
  const tables = locales
    .map(
      (locale) =>
        `    LocaleTable {\n        locale: "${locale}",\n        entries: &[\n${flattened[locale].map((entry) => rustEntry(entry)).join('\n')}\n        ],\n    },`,
    )
    .join('\n')
  return `//! GENERATED by \`npm run desktop:l10n\` (M111 lane IN, D91.20) — do not edit.
//!
//! The fifteen UI tables as flat dotted-key maps, in English key order. The
//! crate's \`text\` reads the current locale's map with an English fallback;
//! \`check:l10n\` fails a stale file.

pub struct LocaleTable {
    pub locale: &'static str,
    pub entries: &'static [(&'static str, &'static str)],
}

#[rustfmt::skip]
pub static TABLES: &[LocaleTable] = &[
${tables}
];
`
}

/**
The singleton's script: dotted-key lookup with an English fallback, the
locale's text direction from real Qt locale data, and Qt locale formatting
for numbers and dates. The tables below are generated; this script is fixed.
*/
const QML_SCRIPT = `    property string localeName: "en"

    function text(key) {
        const parts = key.split(".")
        for (const name of [localeName, "en"]) {
            let node = tables[name]
            for (const part of parts) {
                if (node === undefined || node === null || typeof node !== "object")
                    break
                node = node[part]
            }
            if (typeof node === "string")
                return node
        }
        return key
    }

    function isRtl(locale) {
        const name = locale === undefined ? localeName : locale
        return Qt.locale(name).textDirection === Qt.RightToLeft
    }

    function formatNumber(value, decimals) {
        const places = decimals === undefined ? 2 : decimals
        return Qt.locale(localeName).toString(value, "f", places)
    }

    function formatDate(year, month, day) {
        return Qt.locale(localeName).toString(new Date(year, month - 1, day), "dd MMM yyyy")
    }
`

function renderQml(locales, nested) {
  const tables = JSON.stringify(
    Object.fromEntries(locales.map((locale) => [locale, nested[locale]])),
  )
  return `// GENERATED by \`npm run desktop:l10n\` (M111 lane IN, D91.20) — do not edit.
pragma Singleton
import QtQml

QtObject {
    readonly property var tables: (${tables})
${QML_SCRIPT}}
`
}

/**
The fifteen UI tables: English from source, the fourteen translations from
their JSON files. Every table carries the same keys in English order (the
localization gate enforces it); the generators trust that order.
*/
export async function loadTables(repoRoot) {
  const { EN, TABLE_DIRECTORY, TABLE_LOCALES, isPluralForms, tableFileName } =
    await loadL10n(repoRoot)
  const locales = [ENGLISH_LOCALE, ...TABLE_LOCALES]
  const nested = { [ENGLISH_LOCALE]: EN }
  for (const locale of TABLE_LOCALES) {
    const file = path.join(repoRoot, TABLE_DIRECTORY, tableFileName(locale))
    nested[locale] = JSON.parse(readFileSync(file, 'utf8'))
  }
  const flattened = Object.fromEntries(
    locales.map((locale) => [locale, flattenTable(nested[locale], isPluralForms)]),
  )
  return { locales, nested, flattened }
}

/** Both generated outputs for already-loaded tables, as relative file paths with text. */
export function renderAll({ locales, nested, flattened }) {
  return [
    { file: RUST_TABLES_FILE, text: renderRust(locales, flattened) },
    { file: QML_SINGLETON_FILE, text: renderQml(locales, nested) },
  ]
}

/** Both generated outputs, as absolute paths with their exact bytes. */
export async function generateAll(repoRoot) {
  const loaded = await loadTables(repoRoot)
  return renderAll(loaded).map(({ file, text }) => ({ file: path.join(repoRoot, file), text }))
}
